// Fetch once at release time; clients never send salary or dates to a calendar API.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const datasetPath = new URL('data/china-calendar.json', root);
const args = process.argv.slice(2);
const reviewed = JSON.parse(await readFile(new URL('data/china-statutory-days.json', root), 'utf8'));
let dataset;
if (args.includes('--check')) {
  dataset = JSON.parse(await readFile(datasetPath, 'utf8'));
} else {
  const years = args.length ? args.map(Number) : [2025, 2026];
  assert.ok(years.every(y => Number.isInteger(y) && y >= 2025 && y <= 2100), 'Use explicit announced years, starting in 2025');
  dataset = { schemaVersion: 1, retrievedAt: new Date().toISOString(), provider: 'Timor',
    documentation: 'https://timor.tech/api/holiday/',
    statutoryRule: 'https://www.gov.cn/zhengce/content/202411/content_6986380.htm', years: {} };
  for (const year of years) {
    assert.equal(reviewed.years[year]?.length, 13, `Review the statutory dates for ${year} before importing`);
    const statutory = new Set(reviewed.years[year]);
    const source = `https://timor.tech/api/holiday/year/${year}/`;
    const reference = `https://raw.githubusercontent.com/NateScarlet/holiday-cn/master/${year}.json`;
    const [primary, secondary] = await Promise.all([source, reference].map(async url => {
      const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
      assert.equal(response.status, 200, url); return response.json();
    }));
    assert.equal(primary.code, 0); assert.equal(secondary.year, year);
    assert.ok(secondary.papers?.length && secondary.papers.every(p => new URL(p).hostname === 'www.gov.cn'), 'Official annual notice required');
    const days = {}, classificationCorrections = [];
    for (const [key, day] of Object.entries(primary.holiday)) {
      assert.equal(day.date, `${year}-${key}`);
      assert.ok(typeof day.holiday === 'boolean' && [1, 2, 3].includes(day.wage));
      assert.ok(day.holiday ? [2, 3].includes(day.wage) : day.wage === 1);
      const kind = !day.holiday ? 'work' : statutory.has(day.date) ? 'statutory' : 'rest';
      if ((day.wage === 3) !== statutory.has(day.date)) classificationCorrections.push({ date: day.date, apiWage: day.wage, reviewedKind: kind });
      days[day.date] = { name: day.name, kind };
    }
    assert.equal(Object.values(days).filter(d => d.kind === 'statutory').length, 13, 'Review statutory-day rules if annual total changes');
    for (const date of statutory) assert.equal(days[date]?.kind, 'statutory', `Statutory date missing: ${date}`);
    assert.equal(Object.keys(days).length, secondary.days.length, 'Providers disagree about exception dates');
    for (const day of secondary.days) {
      assert.ok(Object.hasOwn(days, day.date), `Missing exception date: ${day.date}`);
      assert.equal(days[day.date].kind !== 'work', day.isOffDay, `Providers disagree: ${day.date}`);
    }
    dataset.years[year] = { source, crossCheckedWith: reference, officialNotices: secondary.papers, classificationCorrections, days };
  }
  await mkdir(new URL('data/', root), { recursive: true });
  await writeFile(datasetPath, JSON.stringify(dataset, null, 2) + '\n');
}
for (const [year, record] of Object.entries(dataset.years)) {
  assert.deepEqual(Object.keys(record.days).filter(date => record.days[date].kind === 'statutory').sort(),
    [...reviewed.years[year]].sort(), `${year} data does not match reviewed statutory dates`);
}
const json = JSON.stringify(dataset, null, 2);
const outputs = [
  ['web/public/china-calendar.mjs', `// Generated by scripts/update-china-calendar.mjs. Do not edit.\nexport const chinaCalendar = ${json};\n`],
  ['macos/Sources/PayPulseCore/ChinaCalendarData.swift', `// Generated by scripts/update-china-calendar.mjs. Do not edit.\nenum ChinaCalendarData {\n    static let json = #"""\n${json}\n"""#\n}\n`],
];
for (const [path, content] of outputs) {
  if (args.includes('--check')) assert.equal(await readFile(new URL(path, root), 'utf8'), content, `${path} is stale`);
  else await writeFile(new URL(path, root), content);
}
console.log(`China calendar ${Object.keys(dataset.years).join(', ')}: ${args.includes('--check') ? 'generated data matches' : 'fetched, cross-checked and generated'}`);
